import {createRequire} from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(process.env.TEST_NODE_MODULES+'/package.json');
const {JSDOM}=require('jsdom');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'));
const panel=dom.window.document.querySelector('.anatomy-panel');
const iframe=panel.querySelector('iframe');
assert(iframe.title);
const url=new URL(iframe.src);
assert.equal(url.origin,'https://sketchfab.com');
assert.equal(url.searchParams.get('animation_autoplay'),'0');
assert(iframe.hasAttribute('allowfullscreen'));
assert(panel.querySelector('.anatomy-credit a').href.includes('9b0b079953b840bc9a13f524b60041e4'));
assert(!panel.querySelector('svg'));
assert(!dom.window.document.querySelector('script[src="anatomy-viewer.js"]'));
assert(!dom.window.document.querySelector('#treatments'));
dom.window.close();
console.log('PASS accessible inline 3D embed, paused animation, provider fallback and old viewer removal');
